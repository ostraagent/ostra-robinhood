// Writes src/abi.ts from the Foundry build of the contracts (../out, made by
// `forge build` in the repository root): the ABI of every Ostra contract the
// SDK calls, and the BeaconProxy creation code a vault address is derived
// from. Run after any contract change:
//   node scripts/abi.ts
// test/abi.test.ts fails while src/abi.ts differs from what this writes.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/** Exported name -> [source file, contract name] in out/<file>/<contract>.json. */
export const CONTRACTS: Readonly<Record<string, readonly [string, string]>> = {
  ostraVaultAbi: ["OstraVault.sol", "OstraVault"],
  ostraVaultFactoryAbi: ["OstraVaultFactory.sol", "OstraVaultFactory"],
  ostraPoolAbi: ["OstraPool.sol", "OstraPool"],
  ostraSplitAbi: ["OstraSplit.sol", "OstraSplit"],
  ostraSplitFactoryAbi: ["OstraSplit.sol", "OstraSplitFactory"],
  x402BatchSettlementAbi: ["IX402BatchSettlement.sol", "IX402BatchSettlement"],
  upgradeableBeaconAbi: ["UpgradeableBeacon.sol", "UpgradeableBeacon"],
  beaconProxyAbi: ["BeaconProxy.sol", "BeaconProxy"],
  ostraLaunchpadAbi: ["OstraLaunchpad.sol", "OstraLaunchpad"],
  ostraDevBuyAbi: ["OstraDevBuy.sol", "OstraDevBuy"],
  ostraHookAbi: ["OstraHook.sol", "OstraHook"],
  ostraTokenAbi: ["OstraToken.sol", "OstraToken"],
  ostraAirdropAbi: ["OstraAirdrop.sol", "OstraAirdrop"],
  ostraVestingAbi: ["OstraVesting.sol", "OstraVesting"],
  ostraDispatcherAbi: ["OstraDispatcher.sol", "OstraDispatcher"],
  ostraCreatorSplitAbi: ["OstraCreatorSplit.sol", "OstraCreatorSplit"],
  ostraLockerAbi: ["OstraLocker.sol", "OstraLocker"],
};

/** The launchpad's contracts (src/launchpad/). */
const LAUNCHPAD_CONTRACTS = new Set([
  "ostraLaunchpadAbi",
  "ostraDevBuyAbi",
  "ostraHookAbi",
  "ostraTokenAbi",
  "ostraAirdropAbi",
  "ostraVestingAbi",
  "ostraDispatcherAbi",
  "ostraCreatorSplitAbi",
  "ostraLockerAbi",
]);

type Artifact = { abi: unknown[]; bytecode: { object: string } };

export function readArtifact(outDir: string, file: string, contract: string): Artifact {
  const artifact = JSON.parse(readFileSync(`${outDir}/${file}/${contract}.json`, "utf8")) as Artifact;
  if (!Array.isArray(artifact.abi)) throw new Error(`${file}/${contract}: no ABI`);
  return artifact;
}

/** The text of src/abi.ts for the build in `outDir`. */
export function abiSource(outDir: string): string {
  const lines = [
    "// Generated by scripts/abi.ts from the Foundry build (out/); do not edit.",
    "// Regenerate with `node scripts/abi.ts` after `forge build`.",
    "",
    'import type { Hex } from "viem";',
    "",
  ];
  for (const [name, [file, contract]] of Object.entries(CONTRACTS)) {
    const { abi } = readArtifact(outDir, file, contract);
    const source = file === "IX402BatchSettlement.sol" ? `interfaces/${file}` : name.startsWith("ostra") && LAUNCHPAD_CONTRACTS.has(name) ? `launchpad/${file}` : file;
    lines.push(`/** ${contract} (src/${source}). */`);
    lines.push(`export const ${name} = ${JSON.stringify(abi, null, 2)} as const;`, "");
  }
  const proxy = readArtifact(outDir, "BeaconProxy.sol", "BeaconProxy").bytecode.object;
  if (!/^0x[0-9a-f]+$/.test(proxy)) throw new Error("BeaconProxy: no creation code");
  lines.push("/** BeaconProxy creation code (OpenZeppelin 5.7.0): OstraVaultFactory derives vault addresses from it. */");
  lines.push(`export const BEACON_PROXY_CREATION_CODE: Hex = "${proxy}";`, "");
  return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const sdk = fileURLToPath(new URL("..", import.meta.url));
  writeFileSync(`${sdk}/src/abi.ts`, abiSource(`${sdk}/../out`));
  console.log("wrote src/abi.ts");
}
